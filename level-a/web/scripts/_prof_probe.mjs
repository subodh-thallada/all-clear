import { chromium } from "playwright-core";
const browser = await chromium.launch({ executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true, args: ["--use-angle=d3d11","--enable-gpu","--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
await page.goto(process.argv[2], { waitUntil: "load" });
await page.waitForSelector('[data-ready="1"]', { timeout: 120000 });
await page.waitForTimeout(4000);
const cdp = await page.context().newCDPSession(page);
await cdp.send("Profiler.enable");
await cdp.send("Profiler.setSamplingInterval", { interval: 200 });
await cdp.send("Profiler.start");
const fps = await page.evaluate(() => new Promise(res => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 5000) requestAnimationFrame(f); else res(n / ((performance.now()-t0)/1000)); }; requestAnimationFrame(f); }));
const { profile } = await cdp.send("Profiler.stop");
console.log("fps", fps);
const self = new Map(); const total = profile.samples.length;
const byId = new Map(profile.nodes.map(n => [n.id, n]));
const counts = new Map(); for (const s of profile.samples) counts.set(s, (counts.get(s) || 0) + 1);
for (const [id, c] of counts) { const n = byId.get(id); const k = `${n.callFrame.functionName || "(anon)"} ${n.callFrame.url.split("/").slice(-1)[0]}:${n.callFrame.lineNumber}`; self.set(k, (self.get(k) || 0) + c); }
const top = [...self.entries()].sort((a, b) => b[1] - a[1]).slice(0, 25);
for (const [k, c] of top) console.log((100 * c / total).toFixed(1).padStart(5), "%", k);
await browser.close();
