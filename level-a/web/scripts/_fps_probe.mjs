import { chromium } from "playwright-core";
const browser = await chromium.launch({ executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true, args: ["--use-angle=d3d11","--enable-gpu","--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: +process.argv[3] || 1280, height: +process.argv[4] || 720 } });
page.on("pageerror", e => console.log("pageerror", e.message));
page.on("console", m => { if (m.type()==="error"||m.type()==="warning") console.log(m.type(), m.text().slice(0,300)); });
await page.goto(process.argv[2], { waitUntil: "load" });
await page.waitForSelector("canvas", { timeout: 60000 });
const t = Date.now();
await page.waitForSelector('[data-ready="1"]', { timeout: 120000 });
console.log("ready after", Date.now()-t);
const frames = await page.evaluate(() => new Promise(res => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 8000) requestAnimationFrame(f); else res(n / ((performance.now()-t0)/1000)); }; requestAnimationFrame(f); }));
console.log("fps", frames);
await browser.close();
